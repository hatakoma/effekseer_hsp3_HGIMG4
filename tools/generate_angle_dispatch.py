"""Developer helper; generated C++ is shipped, Python not required to build."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
header = Path(r'C:\Program Files (x86)\Windows Kits\10\Include\10.0.22621.0\um\gl\GL.h').read_text()
sources = list((root/'vendor/Effekseer/Dev/Cpp/EffekseerRendererGL').rglob('*.cpp')) + [root/'src/bridge.cpp']
used = set()
for source in sources:
    used.update(re.findall(r'(?<![\w:])(gl[A-Z]\w+)\s*\(', source.read_text(encoding='utf-8-sig')))
out = ['// Generated by tools/generate_angle_dispatch.py. ES2 base-API dispatch.\n',
       '#include "angle_gl.h"\n#include <stdexcept>\n']
for result, name, params in re.findall(r'WINGDIAPI\s+(.+?)\s+APIENTRY\s+(gl\w+)\s*\(([^;]*)\);', header):
    if name not in used:
        continue
    params = ' '.join(params.split())
    args = [] if params == 'void' else [re.findall(r'\b(\w+)\s*(?:\[[^]]*\])?$', p.strip())[0] for p in params.split(',')]
    out.append(f'{result} APIENTRY {name}({params}) {{\n'
               f'    static auto fn = reinterpret_cast<decltype(&::{name})>(efk_angle_proc("{name}"));\n'
               f'    if (!fn) throw std::runtime_error("ANGLE entry point unavailable: {name}");\n'
               f'    return fn({", ".join(args)});\n}}\n')
(root/'src/angle_dispatch.cpp').write_text(''.join(out), encoding='utf-8')
